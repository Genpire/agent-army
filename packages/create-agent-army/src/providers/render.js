// Render: the CLI can't create a service from a Blueprint, and Blueprints can't be created by API,
// so this opens "Deploy to Render" (the repo's render.yaml) and says what to fill in.
import { RENDER_DEPLOY_URL } from "../constants.js";

/** @typedef {import("../types.js").Provider} Provider */
/** @typedef {import("../types.js").Context} Context */

/**
 * Asks for the address the user sees in the provider's page, so the installer can wait for it.
 * @param {Context} ctx
 * @param {string} question
 * @returns {Promise<string | undefined>}
 */
export async function askForUrl(ctx, question) {
  if (!ctx.prompt.interactive || ctx.run.dryRun) return undefined;
  for (;;) {
    const answer = (await ctx.prompt.ask(question, "")).trim().replace(/\/+$/, "");
    if (!answer) return undefined;
    const url = /^https?:\/\//.test(answer) ? answer : `https://${answer}`;
    try {
      const parsed = new URL(url);
      if (parsed.hostname.includes(".")) return `${parsed.protocol}//${parsed.host}`;
    } catch {
      // ask again
    }
    ctx.out.line("That doesn't look like an address, e.g. https://agent-army.onrender.com");
  }
}

/** @type {Provider} */
export const render = {
  id: "render",
  label: "Render",
  installUrl: "https://render.com/docs/cli",
  loginCommand: "render login",
  requiresCli: () => false,

  plan: ({ options }) =>
    `Render Blueprint ${options.name}, set up in your browser: one web service with a disk (2c-8g, about $135/month; 2c-4g about $85/month).`,

  async deploy(ctx) {
    const { name } = ctx.options;
    ctx.out.step("Opening Deploy to Render in your browser");
    ctx.out.line("The Render CLI can't create services from a Blueprint, so this part happens on render.com.");
    await ctx.openUrl(RENDER_DEPLOY_URL);
    ctx.out.line();
    ctx.out.line("On that page:");
    ctx.out.line("  1. Sign in (GitHub works) and add a payment method: a service with a disk needs a paid plan.");
    ctx.out.line(`  2. Blueprint Name: ${name}. The service is called agent-army; its address becomes`);
    ctx.out.line("     https://<service name>.onrender.com (Render adds a suffix when the name is taken).");
    ctx.out.line("  3. Plan: 2c-8g runs 3 repo tasks at once. 2c-4g is cheaper: then set Settings > Repo task");
    ctx.out.line("     limits > Max parallel to 1 in Agent Army.");
    ctx.out.line("  4. Click Deploy Blueprint. Render builds the image from the repository (15 to 25 minutes).");
    ctx.out.line("  5. Render generates MASTER_KEY and SETUP_TOKEN. Open the service > Environment: copy SETUP_TOKEN");
    ctx.out.line("     to sign in, and save MASTER_KEY in a password manager: it decrypts your data.");
    ctx.out.line();

    const url = await askForUrl(ctx, "Paste the service's address once Render shows it as Live (Enter to skip)");
    return {
      url,
      waitForHealth: Boolean(url),
      setupTokenHint: "Render > the agent-army service > Environment > SETUP_TOKEN",
      masterKeyHint: "Render > the agent-army service > Environment > MASTER_KEY (generated by Render: keep a copy safe)",
      notes: [
        "Update: Render > the service > Manual Deploy > Deploy latest commit (auto-deploy is off).",
        "Remove: Render > the service > Settings > Delete Web Service (deletes the disk and its data).",
      ],
      notHealthyHint: "Render > the service > Events and Logs show the build and the start.",
    };
  },
};
